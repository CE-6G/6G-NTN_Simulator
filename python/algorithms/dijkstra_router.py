"""Dijkstra-based routing with selectable edge cost metrics."""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Dict, List, Optional, Tuple

import networkx as nx
import logging
logger = logging.getLogger(__name__)

class CostMetric(Enum):
    """Supported cost metrics for Dijkstra shortest path."""

    MIN_HOP = "min_hop"
    TOTAL_DELAY_MS = "total_delay_ms"
    DISTANCE_KM = "distance_km"


@dataclass
class RouteResult:
    """Routing outcome returned to API consumers."""

    source: str
    destination: str
    path: List[str]
    total_cost: float
    hop_count: int
    metric: str
    success: bool
    error: Optional[str] = None


class DijkstraRouter:
    """Shortest-path router over dynamic topology data."""

    def build_graph(self, links: List[Dict[str, object]], metric: CostMetric, nodes: Optional[Dict] = None, buffer_size: float = 256, packet_size_bytes: float = 1500,) -> nx.DiGraph:
        """Create a directed graph where edge weight depends on the selected metric.

        Using a DiGraph (directional graph) is required for TOTAL_DELAY_MS because queueing delay
        depends on the transmitting node's traffic load, which differs by
        direction (e.g. satellite1->satellite2 vs satellite2->satellite1).
        """
        if nodes is None:
            nodes = {}

        logger.debug('Creating graph of network topology for routing purposes')
        graph = nx.DiGraph()

        for link in links:
            src = str(link["source"])
            dst = str(link["target"])
            delay_ms_propagation = float(link.get("delay_ms", 0.0))
            distance_km = float(link.get("distance_km", 0.0))

            if metric == CostMetric.MIN_HOP:
                forward_weight = 1.0
                reverse_weight = 1.0
            elif metric == CostMetric.DISTANCE_KM:
                forward_weight = distance_km
                reverse_weight = distance_km
            else:
                # Forward direction: traffic generated by src
                forward_queueing = self._extract_queueing_delay(
                    nodes,
                    link,
                    packet_size_bytes=packet_size_bytes,
                )
                forward_loss_penalty = self._extract_loss_penalty(
                    nodes,
                    link,
                    buffer_size=buffer_size,
                    packet_size_bytes=packet_size_bytes,
                )

                # Reverse direction: traffic generated by dst
                reverse_link = dict(link)
                reverse_link["source"] = dst
                reverse_link["target"] = src

                reverse_queueing = self._extract_queueing_delay(
                    nodes,
                    reverse_link,
                    packet_size_bytes=packet_size_bytes,
                )
                reverse_loss_penalty = self._extract_loss_penalty(
                    nodes,
                    reverse_link,
                    buffer_size=buffer_size,
                    packet_size_bytes=packet_size_bytes,
                )

                forward_weight = delay_ms_propagation + forward_queueing + forward_loss_penalty
                reverse_weight = delay_ms_propagation + reverse_queueing + reverse_loss_penalty

            graph.add_edge(
                src, dst,
                weight=forward_weight,
                delay_ms=delay_ms_propagation,
                distance_km=distance_km,
            )
            graph.add_edge(
                dst, src,
                weight=reverse_weight,
                delay_ms=delay_ms_propagation,
                distance_km=distance_km,
            )

        return graph

    def compute_route(
        self,
        links: List[Dict[str, object]],
        source: str,
        destination: str,
        metric: CostMetric,
        nodes: Optional[Dict] = None,
        buffer_size: float = 256,
        packet_size_bytes: float = 1500,
    ) -> RouteResult:
        """Compute route and aggregate path statistics."""
        source = str(source)
        destination = str(destination)
        graph = self.build_graph(
            links=links,
            metric=metric,
            nodes=nodes,
            buffer_size=buffer_size,
            packet_size_bytes=packet_size_bytes,
        )   

        if source not in graph or destination not in graph:
            logger.debug('Problem while creating graph: source_or_destination_not_in_graph')
            return RouteResult(
                source=source,
                destination=destination,
                path=[],
                total_cost=0.0,
                hop_count=0,
                metric=metric.value,
                success=False,
                error="source_or_destination_not_in_graph",
            )

        try:
            path = nx.shortest_path(graph, source, destination, weight="weight")
            total_cost = nx.shortest_path_length(graph, source, destination, weight="weight")
            hop_count = max(0, len(path) - 1)
            logger.debug('Successfully performed routing algorithm')
            return RouteResult(
                source=source,
                destination=destination,
                path=path,
                total_cost=float(total_cost),
                hop_count=hop_count,
                metric=metric.value,
                success=True,
            )
        except nx.NetworkXNoPath:
            logger.warning('Error in the routing algorithm: no path found from source to destination')
            return RouteResult(
                source=source,
                destination=destination,
                path=[],
                total_cost=0.0,
                hop_count=0,
                metric=metric.value,
                success=False,
                error="no_path",
            )
        
    def _extract_queueing_delay(
        self,
        nodes: Dict[str, float],
        link: Dict[str, object],
        packet_size_bytes: float = 1500,
    ) -> float:
        """
        Estimate queueing delay in ms from background traffic on the link source.
        This function returns only the queueing component.
        """
        src_id = str(link.get("source"))
        bg_rate_mbps = float(nodes.get(src_id, 0.0))
        capacity_mbps = float(link.get("capacity_mbps", 1.0))

        if bg_rate_mbps <= 0 or capacity_mbps <= 0 or packet_size_bytes <= 0:
            return 0.0

        rho = bg_rate_mbps / capacity_mbps
        rho = min(max(rho, 0.0), 0.999)

        service_time_s = (packet_size_bytes * 8.0) / (capacity_mbps * 1e6)
        queueing_delay_s = service_time_s * (rho / max(1e-9, 1.0 - rho))

        return queueing_delay_s * 1000.0


    def _extract_loss_penalty(
        self,
        nodes: Dict[str, float],
        link: Dict[str, object],
        buffer_size: float = 256,
        packet_size_bytes: float = 1500,
    ) -> float:
        """
        Estimate a loss-risk penalty in ms-equivalent units.

        The penalty is not a physical delay; it is an added routing cost that
        becomes significant when utilization approaches or exceeds saturation.
        """
        src_id = str(link.get("source"))
        bg_rate_mbps = float(nodes.get(src_id, 0.0))
        capacity_mbps = float(link.get("capacity_mbps", 1.0))

        if bg_rate_mbps <= 0 or capacity_mbps <= 0 or packet_size_bytes <= 0 or buffer_size <= 0:
            return 0.0

        rho = max(0.0, bg_rate_mbps / capacity_mbps)
        service_time_s = (packet_size_bytes * 8.0) / (capacity_mbps * 1e6)

        # Approximate time needed to drain a full buffer.
        buffer_drain_time_s = buffer_size * service_time_s

        # Below 50% utilization, keep the penalty near zero.
        # Between 50% and 100%, ramp up sharply.
        # Above 100%, penalize very aggressively.
        if rho < 0.5:
            penalty_s = 0.0
        elif rho < 1.0:
            x = (rho - 0.5) / 0.3
            penalty_s = (x ** 2) * buffer_drain_time_s
        else:
            overflow = rho - 1.0
            penalty_s = buffer_drain_time_s * (1.0 + 10.0 * overflow)

        return penalty_s * 1000.0